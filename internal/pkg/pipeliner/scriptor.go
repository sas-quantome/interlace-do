package pipeliner

import (
	"bytes"
	"fmt"
	"os"
	"os/exec"
	"path"
	"strings"
	"time"
)

// Scriptor is a type for generating job scripts in the event function folder.
type Scriptor struct {
	sopHead  string // sopHead is the SOP head program name orchestrating the pipeline
	funPath  string // funPath is the event function folder (e.g., scripts)
	actPath  string // actPath is the event active folder (e.g., logs)
	jobName  string // JobName is the unique job name identifier
	jobIndex int    // jobIndex tracks the current job index used for ordering unique job names.
	apsIndex int    // apsIndex is the DAG vertex index of the application being executed.
	maxHours int    // maxHours is the maximum number of hours allowed for the job.
	delta    int    // delta used internally.
	nArgs    int    // nArgs counts the number of arguments assigned to the command line.
	timeTick []time.Duration
	buf      bytes.Buffer
}

// NewScriptor creates and initializes a new Scriptor instance for generating job scripts.
func NewScriptor(actPath, funPath, sopHead string) *Scriptor {
	return &Scriptor{
		actPath:  actPath,
		funPath:  funPath,
		sopHead:  sopHead,
		maxHours: 1,
		timeTick: timeTicker(),
	}
}

// NewHeader resets the buffer and writes the script header with program information.
func (scr *Scriptor) NewHeader() {
	scr.nArgs = 0
	scr.buf.Reset()
	_, _ = fmt.Fprintf(&scr.buf, "#!/bin/bash\n#\n# This script is generated by: %s\n\n",
		scr.sopHead)
}

// NewJobName generates a unique job name requiring the indexes, the workflowID, and the application name.
// The optional suffix can be used to further distinguish the job name e.g., for CID (content ID) segments.
func (scr *Scriptor) NewJobName(jix, aix, delta int, wid, app, sfx string) {
	scr.jobIndex = jix
	scr.apsIndex = aix
	scr.delta = delta
	if sfx != "" {
		scr.jobName = fmt.Sprintf("j%05d_%s_%s_%s", jix, wid, app, strings.ToLower(sfx))
	} else {
		scr.jobName = fmt.Sprintf("j%05d_%s_%s", jix, wid, app)
	}
}

// JobName returns the job name generated by the Scriptor.
func (scr *Scriptor) JobName() string {
	return scr.jobName
}

// SaveScript writes the scriptor's buffer script file in the event function folder using the job name as the file name.
func (scr *Scriptor) SaveScript() error {
	fp := fmt.Sprintf("%s/%s", scr.funPath, scr.jobName)
	scr.buf.WriteRune('\n')
	return os.WriteFile(fp, scr.buf.Bytes(), 0744)
}

// MaxHours returns the maximum number of hours allowed for the job.
func (scr *Scriptor) MaxHours() int {
	return scr.maxHours
}

// UpdateMaxHours updates the maximum number of hours allowed for the job.
func (scr *Scriptor) UpdateMaxHours(maxHours int) {
	scr.maxHours = maxHours
}

// SlurmParameters writes the active Slurm kv-tab-delimited parameters to the scriptor's buffer, including err and out file paths.
func (scr *Scriptor) SlurmParameters(p []string) {
	if len(p) > 0 {
		scr.buf.WriteString("#Active comments for Slurm:\n")
		for _, v := range p {
			if s := strings.Split(v, "\t"); len(s) == 2 {
				if strings.HasPrefix(s[0], "--") {
					_, _ = fmt.Fprintf(&scr.buf, "#SBATCH %s=%s\n", s[0], s[1])
				} else {
					_, _ = fmt.Fprintf(&scr.buf, "#SBATCH %s %s\n", s[0], s[1])
				}
			}
		}
		_, _ = fmt.Fprintf(&scr.buf, "#SBATCH --error=%s/%s.err\n", scr.funPath, scr.jobName)
		_, _ = fmt.Fprintf(&scr.buf, "#SBATCH --output=%s/%s.out\n", scr.funPath, scr.jobName)
		_, _ = fmt.Fprintf(&scr.buf, "#SBATCH --job-name=%s\n\n", scr.jobName)
	}
}

// PbsParameters writes the active PBS kv-tab-delimited parameters to the scriptor's buffer, including err and out file paths.
func (scr *Scriptor) PbsParameters(p []string) {
	if len(p) > 0 {
		if len(p) > 0 {
			scr.buf.WriteString("#Active comments for PBS:\n")
			for _, v := range p {
				if s := strings.Split(v, "\t"); len(s) == 2 {
					_, _ = fmt.Fprintf(&scr.buf, "#PBS %s %s\n", s[0], s[1])
				}
			}
			_, _ = fmt.Fprintf(&scr.buf, "#PBS -e %s/%s.err\n", scr.funPath, scr.jobName)
			_, _ = fmt.Fprintf(&scr.buf, "#PBS -o %s/%s.out\n", scr.funPath, scr.jobName)
			_, _ = fmt.Fprintf(&scr.buf, "#PBS -N %s\n\n", scr.jobName)
		}
	}
}

// BinPath writes the application binary path to the scriptor's buffer, using the provided binPath if not empty.
func (scr *Scriptor) BinPath(binPath, appName string) {
	if binPath != "" {
		_, _ = fmt.Fprintf(&scr.buf, "%s/%s", binPath, appName)
	} else {
		scr.buf.WriteString(appName)
	}
}

// Flags write the active flags to the scriptor's buffer.'
func (scr *Scriptor) Flags(p []string) {
	if len(p) > 0 {
		for _, v := range p {
			_, _ = fmt.Fprintf(&scr.buf, " %s", v)
		}
		scr.nArgs++
	}
}

// LogFile writes the log file path to the scriptor's buffer, using the job name as the file name.
func (scr *Scriptor) LogFile(p []string) {
	if len(p) > 0 {
		for _, v := range p {
			if strings.HasPrefix(v, "-log") || strings.HasPrefix(v, "-L") {
				scr.newLine()
				_, _ = fmt.Fprintf(&scr.buf, "-log %s/%s.log",
					scr.actPath, scr.jobName)
				scr.nArgs++
				return
			}
			if strings.HasPrefix(v, "log") || strings.HasPrefix(v, "L") {
				scr.newLine()
				_, _ = fmt.Fprintf(&scr.buf, "2>> %s/%s.log \\\n1>> %s/%s.txt",
					scr.actPath, scr.jobName, scr.actPath, scr.jobName)
				scr.nArgs++
				return
			}
		}
	}
}

// OptParameters appends parameters to the script buffer, skipping those with prefixes "-log" or "log".
func (scr *Scriptor) OptParameters(p []string) {
	scr.ReqParameters(p)
}

// ReqParameters appends required parameters to the script buffer.
func (scr *Scriptor) ReqParameters(p []string) {
	if len(p) > 0 {
		for _, v := range p {
			if strings.HasPrefix(v, "-log") || strings.HasPrefix(v, "log") || strings.HasPrefix(v, "-L") || strings.HasPrefix(v, "L") {
				continue
			}
			s := strings.Split(v, "\t")
			switch len(s) {
			case 2:
				if s[1] == "." {
					continue
				}
				scr.newLine()
				_, _ = fmt.Fprintf(&scr.buf, "%s %s", s[0], s[1])
				scr.nArgs++
			case 1:
				scr.newLine()
				_, _ = fmt.Fprintf(&scr.buf, "%s", s[0])
				scr.nArgs++
			}
		}
	}
}

// BoxParameters appends the parallel job box parameter to the script buffer.
func (scr *Scriptor) BoxParameters(arg, par string) {
	scr.newLine()
	_, _ = fmt.Fprintf(&scr.buf, "%s %s", arg, par)
	scr.nArgs++
}

func (scr *Scriptor) newLine() {
	if scr.nArgs > 0 {
		scr.buf.WriteString(" \\\n")
	} else {
		scr.buf.WriteString(" ")
	}
}

// run executes the job script using the provided interpreter.
func (scr *Scriptor) run(interpreter string) error {
	cmd := exec.Command(interpreter, fmt.Sprintf("%s/%s", scr.funPath, scr.jobName))
	return cmd.Run()
}

// submit submits a job-scheduled script, it persists 10 times in case the scheduler is not responding.
func (scr *Scriptor) submit(interpreter string) error {
	time.Sleep(300 * time.Millisecond)
	for i := 1; i < 10; i++ {
		if err := scr.run(interpreter); err == nil {
			return nil
		}
		time.Sleep(time.Duration(i) * 30 * time.Second)
		if _, err := os.Stat(path.Join(scr.actPath, scr.jobName+".err")); !os.IsNotExist(err) {
			break
		}
	}
	return fmt.Errorf("%s job scheduler failed submitting: %s", interpreter, scr.jobName)
}

// waitSchedulerFinishes searches the done (marker) file to find out if the scheduler has finished submitting the job.
func (scr *Scriptor) waitSchedulerFinishes(err error) error {
	if err != nil {
		return err
	}
	done := path.Join(scr.actPath, scr.jobName+".done")
	// 65-minute cycle
	for i := range 10 {
		if _, ret := os.Stat(done); ret == nil {
			return nil
		}
		scr.SigmoidSlowDown(i, 30)
	}
	m := scr.maxHours*60 - 65
	if m > 0 {
		// check every 15 minutes
		const M = 15
		N := m / M
		for range N {
			if _, ret := os.Stat(done); ret == nil {
				return nil
			}
			time.Sleep(M * time.Minute)
		}
	}
	return fmt.Errorf("time out [max=%dh] and file not found: %s", scr.maxHours, done)
}

// SigmoidSlowDown introduces progressive delays based on iteration index `i`, capped at `maxMinutesSleepInterval`.
func (scr *Scriptor) SigmoidSlowDown(i int, maxMinutesSleepInterval time.Duration) {
	if i < len(scr.timeTick) {
		time.Sleep(scr.timeTick[i])
	} else {
		time.Sleep(maxMinutesSleepInterval * time.Minute)
	}
}

// sleepDurations defines a sequence of increasing time intervals used for implementing progressive wait strategies.
func timeTicker() []time.Duration {
	return []time.Duration{
		6 * time.Second,
		9 * time.Second,
		15 * time.Second,
		30 * time.Second,
		1 * time.Minute,
		3 * time.Minute,
		6 * time.Minute,
		9 * time.Minute,
		15 * time.Minute,
		30 * time.Minute,
	}
}
