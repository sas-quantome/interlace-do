func TestNewScriptor(t *testing.T) {
	fp := tester.TestBasePath()
	actPath := path.Join(fp, runner.EventFN, "btc", "w10101", runner.ApolloTimeTag, runner.ActFN)
	funPath := path.Join(fp, runner.EventFN, "btc", "w10101", runner.ApolloTimeTag, runner.FuncFN)
	scr := NewScriptor(actPath, funPath, "a11408")
	require.NotNil(t, scr)
	require.Equal(t, 0, scr.nArgs)
	require.Equal(t, 1, scr.maxHours)
	require.Equal(t, 10, len(scr.timeTick))
	require.Equal(t, actPath, scr.actPath)
	require.Equal(t, funPath, scr.funPath)
	require.Empty(t, scr.jobName)
}

