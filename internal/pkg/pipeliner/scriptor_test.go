func TestScriptor_SigmoidSlowDown(t *testing.T) {
	scr := NewScriptor("", "", "a11408")
	start := time.Now()
	scr.SigmoidSlowDown(0, 1)
	end := time.Now()
	elapsed := end.Sub(start).Seconds()
	require.Equal(t, 6, int(elapsed))
}
